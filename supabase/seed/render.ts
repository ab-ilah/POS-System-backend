import { buildSeed, LOCAL_SEED_PASSWORD, type SeedModel } from "./catalog.ts";
import { sqlInt, sqlJson, sqlString, sqlTextOrNull, sqlUuid } from "./sql.ts";

function renderUsers(model: SeedModel): string {
  const statements: string[] = [];
  for (const user of model.users) {
    statements.push(`insert into auth.users (
  instance_id,
  id,
  aud,
  role,
  email,
  encrypted_password,
  email_confirmed_at,
  raw_app_meta_data,
  raw_user_meta_data,
  created_at,
  updated_at,
  confirmation_token,
  recovery_token,
  email_change,
  email_change_token_new,
  email_change_token_current,
  phone_change,
  phone_change_token,
  reauthentication_token
) values (
  '00000000-0000-0000-0000-000000000000',
  ${sqlUuid(user.id)},
  'authenticated',
  'authenticated',
  ${sqlString(user.email)},
  extensions.crypt(${sqlString(LOCAL_SEED_PASSWORD)}, extensions.gen_salt('bf')),
  now(),
  ${sqlJson({ provider: "email", providers: ["email"], role: user.role })},
  ${sqlJson({ full_name: user.fullName })},
  now(),
  now(),
  '',
  '',
  '',
  '',
  '',
  '',
  '',
  ''
);`);
    statements.push(`insert into public.profiles (id, full_name)
values (${sqlUuid(user.id)}, ${sqlString(user.fullName)})
on conflict (id) do update
set full_name = excluded.full_name;`);
  }
  return statements.join("\n\n");
}

function renderProducts(model: SeedModel): string {
  const productRows = model.products
    .map(
      (product) =>
        `  (${sqlUuid(product.id)}, ${sqlString(product.name)}, ${sqlString(product.category)}, ${sqlString(product.description)}, ${sqlTextOrNull(product.imagePath)})`,
    )
    .join(",\n");
  const variantRows = model.products
    .flatMap((product) => product.variants)
    .map(
      (variant) =>
        `  (${sqlUuid(variant.id)}, ${sqlUuid(variant.productId)}, ${sqlString(variant.sku)}, ${sqlString(variant.sizeName)}, ${sqlString(variant.colourName)}, ${sqlInt(variant.pricePesewas, variant.sku)}, ${sqlInt(variant.stockQty, variant.sku)}, ${sqlInt(variant.lowStockThreshold, variant.sku)})`,
    )
    .join(",\n");
  return `insert into public.products (id, name, category, description, image_path)
values
${productRows};

insert into public.product_variants (
  id,
  product_id,
  sku,
  size_name,
  colour_name,
  price_pesewas,
  stock_qty,
  low_stock_threshold
) values
${variantRows};`;
}

function renderCustomers(model: SeedModel): string {
  const rows = model.customers
    .map(
      (customer) =>
        `  (${sqlUuid(customer.id)}, ${sqlString(customer.fullName)}, ${sqlString(customer.phone)}, ${sqlInt(customer.creditBalancePesewas, customer.fullName)})`,
    )
    .join(",\n");
  return `insert into public.customers (id, full_name, phone, credit_balance_pesewas)
values
${rows};`;
}

function renderSales(model: SeedModel): string {
  const defaultStoreId = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
  const saleRows = model.sales
    .map(
      (sale) =>
        `  (${sqlUuid(sale.id)}, ${sqlString(sale.receiptNo)}, ${sqlUuid(defaultStoreId)}, ${sale.customerId === null ? "null" : sqlUuid(sale.customerId)}, ${sqlUuid(sale.cashierId)}, 'open', ${sqlInt(sale.subtotalPesewas, sale.receiptNo)}, ${sqlInt(sale.totalPesewas, sale.receiptNo)}, ${sqlInt(sale.tenderedPesewas, sale.receiptNo)}, ${sqlInt(sale.changePesewas, sale.receiptNo)}, ${sqlInt(sale.creditAppliedPesewas, sale.receiptNo)})`,
    )
    .join(",\n");
  const itemRows = model.sales
    .flatMap((sale) => sale.items)
    .map(
      (item) =>
        `  (${sqlUuid(item.id)}, ${sqlUuid(item.saleId)}, ${sqlUuid(item.variantId)}, ${sqlString(item.productName)}, ${sqlString(item.sizeName)}, ${sqlString(item.colourName)}, ${sqlInt(item.qty, item.id)}, ${sqlInt(item.unitPricePesewas, item.id)}, ${sqlInt(item.lineTotalPesewas, item.id)})`,
    )
    .join(",\n");
  return `insert into public.stores (id, name)
values (${sqlUuid(defaultStoreId)}, 'Main shop')
on conflict (id) do nothing;

insert into public.sales (
  id,
  receipt_no,
  store_id,
  customer_id,
  cashier_id,
  status,
  subtotal_pesewas,
  total_pesewas,
  tendered_pesewas,
  change_pesewas,
  credit_applied_pesewas
) values
${saleRows};

insert into public.sale_lines (
  id,
  sale_id,
  variant_id,
  product_name,
  size_name,
  colour_name,
  quantity,
  unit_price_pesewas,
  line_total_pesewas
) values
${itemRows};

update public.sales
set status = 'completed'
where id in (${model.sales.map((sale) => sqlUuid(sale.id)).join(", ")});`;
}

export function renderSeedSql(model: SeedModel = buildSeed()): string {
  return `-- Generated by supabase/seed/generate.ts. Do not edit by hand.
-- Regenerate with: npm run seed:generate
-- Local development only. Deploy does not load this file.
-- Passwords below are local fixtures (${LOCAL_SEED_PASSWORD}) and are not hosted secrets.
-- credit_balance_pesewas is the amount the customer currently owes the shop.
-- Historical sales are a snapshot. They do not post again into that balance.
-- supabase db reset applies this file as postgres with no SET ROLE. That session
-- may set credit balances. There is no seed flag a staff or service session can turn on.

${renderUsers(model)}

${renderProducts(model)}

${renderCustomers(model)}

${renderSales(model)}
`;
}
